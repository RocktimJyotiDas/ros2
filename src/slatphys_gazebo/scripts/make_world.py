#!/usr/bin/env python3
"""A Gazebo world with a scene's objects as the SLAT-Phys twin predicts them, plus the
grasps.json (robot `base` frame) and the ground truth the robot code is scored against.

Input: the twin's sim.json (SLAT-Phys reconstruction + materialisation; mesh paths may be relative to
it) and the matching grasps.json in `base` (object positions). Each object becomes a box with the
reconstructed footprint and height (width across the fingers along the grasp yaw), and the
twin's mass. Soft objects (E < 5e7 Pa, the paper's FEM threshold) become two halves joined by a
prismatic spring across the grasp axis (two outer plates), with the stiffness of real2sim/sim_squeeze_model.py:
    k = E * pad_width * h / L      (so a squeeze at F compresses by F / k = F L / (E w h))
compression capped at 0.8 L. Gazebo has no FEM; this keeps the squeeze reading the paper's
contact model predicts. Rigid objects are one link.

Gazebo frames: the robot's base_link is the world origin, and ur_robot_driver's `base` frame is
base_link turned 180 deg about z, so a point (x, y) in base is (-x, -y) in the world. The table
is the ground plane, z = 0 = table_z_base.

--fit_width W scales the whole scene uniformly so its widest grasp is W (masses with the cube):
the photo's metric scale rests on an assumed camera height, and the Hand-E opens 50 mm.

    python3 make_world.py --sim data/twin/img4827/sim.json --grasps data/twin/img4827/grasps.json \
        --out src/slatphys_gazebo/worlds/img4827_fit40 --fit_width 0.040        (scripts/make_worlds.sh)
"""

import argparse
import json
import math
import os

import numpy as np

FEM_MAX_E = 5e7
PAD_W, PAD_HALF, TIP_CLEARANCE = 0.022, 0.020, 0.005  # configs/gazebo.yaml
MAX_STRAIN = 0.8
PLATE = 0.1  # soft objects: plate thickness / width; 2 plates + 0.8 L of travel = L
MU = 1.0


def obj_vertices(path):
    return np.array([[float(v) for v in line.split()[1:4]] for line in open(path) if line.startswith("v ")])


def box_inertia(m, x, y, z):
    return m * (y * y + z * z) / 12, m * (x * x + z * z) / 12, m * (x * x + y * y) / 12


def link(name, pose, m, size, rgba, visual=None):
    """visual: (x offset, size) of a visual-only box, if it differs from the collision box."""
    ixx, iyy, izz = box_inertia(m, *size)
    s = " ".join(f"{v:.5f}" for v in size)
    vpose, vs = "0 0 0 0 0 0", s
    if visual:
        vpose, vs = f"{visual[0]:.5f} 0 0 0 0 0", " ".join(f"{v:.5f}" for v in visual[1])
    return f"""
      <link name="{name}">
        <pose>{" ".join(f"{v:.5f}" for v in pose)}</pose>
        <inertial><mass>{m:.6f}</mass>
          <inertia><ixx>{ixx:.3e}</ixx><iyy>{iyy:.3e}</iyy><izz>{izz:.3e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="c"><geometry><box><size>{s}</size></box></geometry>
          <surface><friction><ode><mu>{MU}</mu><mu2>{MU}</mu2></ode></friction></surface>
        </collision>
        <visual name="v"><pose>{vpose}</pose><geometry><box><size>{vs}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material>
        </visual>
      </link>"""


def model(o, xy_world, yaw_world, rgba):
    w, l, h, m = o["width"], o["length"], o["height"], o["mass_kg"]
    head = f'    <model name="{o["name"]}">\n      <pose>{xy_world[0]:.5f} {xy_world[1]:.5f} 0 0 0 {yaw_world:.5f}</pose>'
    if not o["soft"]:
        return head + link("body", (0, 0, h / 2, 0, 0, 0), m, (w, l, h), rgba) + "\n    </model>\n"
    # Two outer plates (what the fingers touch) on a spring: the fingers can then close by the
    # full 0.8 L (with two half-blocks a finger would run into the other half at L / 2).
    t, half = PLATE * w, m / 2
    damping = 2 * math.sqrt(o["k"] * half)  # about critical: settles without ringing
    # Visuals: each plate carries half of the block, so the object looks solid and shrinks when squeezed.
    dv = w / 4 - t / 2
    return head + link("plate_a", (-(w - t) / 2, 0, h / 2, 0, 0, 0), half, (t, l, h), rgba, (dv, (w / 2, l, h))) + \
        link("plate_b", ((w - t) / 2, 0, h / 2, 0, 0, 0), half, (t, l, h), rgba, (-dv, (w / 2, l, h))) + f"""
      <joint name="spring" type="prismatic">
        <parent>plate_a</parent><child>plate_b</child>
        <axis><xyz>1 0 0</xyz>
          <limit><lower>{-MAX_STRAIN * w:.5f}</lower><upper>0</upper></limit>
          <dynamics><spring_reference>0</spring_reference><spring_stiffness>{o["k"]:.3f}</spring_stiffness>
            <damping>{damping:.4f}</damping></dynamics>
        </axis>
      </joint>
      <plugin filename="gz-sim-joint-state-publisher-system" name="gz::sim::systems::JointStatePublisher"/>
    </model>
"""


WORLD = """<?xml version="1.0"?>
<!-- generated by slatphys_gazebo/scripts/make_world.py from {src} -->
<sdf version="1.9">
  <world name="slatphys">
    <!-- 0.2 ms: the soft objects' plates weigh grams on a stiff spring (period ~3 ms); at 1 ms DART
         passed the wrong force from the fingers to them (compression off by 0.65-1.7x) -->
    <physics name="0.2ms" type="ignored"><max_step_size>0.0002</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-forcetorque-system" name="gz::sim::systems::ForceTorque"/>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><direction>-0.4 0.2 -0.9</direction></light>
    <model name="table">
      <static>true</static>
      <link name="top">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>4 4</size></plane></geometry>
          <surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>4 4</size></plane></geometry>
          <material><ambient>0.55 0.4 0.25 1</ambient><diffuse>0.55 0.4 0.25 1</diffuse></material></visual>
      </link>
    </model>
{models}  </world>
</sdf>
"""


# The lab camera, simulated: straight down, 0.45 m above the table over the objects (README:
# 0.40-0.50 m, over the object area). 1280x720 and ~69 deg horizontal FOV, like the RealSense profile.
TOPCAM = {"height": 0.45, "w": 1280, "h": 720, "hfov": 1.20, "rate": 5}


def rpy_matrix(r, p, y):
    cr, sr, cp, sp, cy, sy = np.cos(r), np.sin(r), np.cos(p), np.sin(p), np.cos(y), np.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp, cp * sr, cp * cr]])


def topcam(centre_world):
    """SDF for a downward camera above centre_world, and its pose as calibrate_camera would report
    it: cam2base in OpenCV axes (x right, y down, z forward)."""
    pose = (centre_world[0], centre_world[1], TOPCAM["height"], 0.0, np.pi / 2, 0.0)  # camera +x points down
    T_world_link = np.eye(4)
    T_world_link[:3, :3], T_world_link[:3, 3] = rpy_matrix(*pose[3:]), pose[:3]
    link_cv = np.array([[0, 0, 1], [-1, 0, 0], [0, -1, 0]], float)  # columns: OpenCV x, y, z in the camera link
    T_world_cv = T_world_link.copy()
    T_world_cv[:3, :3] = T_world_link[:3, :3] @ link_cv
    T_base_world = np.diag([-1.0, -1.0, 1.0, 1.0])  # base = base_link turned 180 deg about z
    sdf = f"""
    <model name="topcam">
      <static>true</static>
      <pose>{" ".join(f"{v:.5f}" for v in pose)}</pose>
      <link name="link">
        <sensor name="topcam" type="camera">
          <always_on>true</always_on>
          <update_rate>{TOPCAM["rate"]}</update_rate>
          <topic>/topcam/image</topic>
          <camera>
            <horizontal_fov>{TOPCAM["hfov"]}</horizontal_fov>
            <image><width>{TOPCAM["w"]}</width><height>{TOPCAM["h"]}</height><format>R8G8B8</format></image>
            <clip><near>0.05</near><far>5</far></clip>
          </camera>
        </sensor>
      </link>
    </model>
"""
    return sdf, (T_base_world @ T_world_cv).tolist()


SENSORS = ('    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">'
           "<render_engine>ogre2</render_engine></plugin>\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sim", required=True, help="the SLAT-Phys twin's sim.json")
    ap.add_argument("--grasps", required=True, help="grasps.json in base (object positions)")
    ap.add_argument("--out", required=True, help="output dir: world.sdf, grasps.json, plan.json")
    ap.add_argument("--fit_width", type=float, default=None, help="scale the scene so the widest grasp is this (m)")
    ap.add_argument("--scene_id", default=None)
    ap.add_argument("--rigid", nargs="*", default=[], help="make these objects rigid (control scenes)")
    ap.add_argument("--topcam", action="store_true",
                    help="add the top-down camera (validates capture + locate) and an object-free world_empty.sdf")
    ap.add_argument("--squeeze_forces", type=float, nargs=2, default=[20.0, 60.0], help="as configs/*.yaml protocol")
    args = ap.parse_args()
    sim, gr = json.load(open(args.sim)), json.load(open(args.grasps))
    table = sim["table"]["height"]

    objs = []
    for o, g in zip(sim["objects"], gr["objects"]):
        assert o["name"] == g["name"], (o["name"], g["name"])
        v = obj_vertices(o["mesh"] if os.path.isabs(o["mesh"]) else os.path.join(os.path.dirname(args.sim), o["mesh"]))
        yaw = o["grasp"]["yaw"]  # sim-world frame, the frame of the mesh
        across, along = np.array([math.cos(yaw), math.sin(yaw)]), np.array([-math.sin(yaw), math.cos(yaw)])
        objs.append({"name": o["name"], "width": float(np.ptp(v[:, :2] @ across)), "length": float(np.ptp(v[:, :2] @ along)),
                     "height": float(v[:, 2].max() - table), "mass_kg": o["mass_kg"], "E": o["E"],
                     "soft": bool(o["E"] is not None and o["E"] < FEM_MAX_E and o["name"] not in args.rigid),
                     "xy_base": g["grasp"]["centre_xy"], "yaw_base": g["grasp"]["yaw"]})
    s = args.fit_width / max(o["width"] for o in objs) if args.fit_width else 1.0
    for o in objs:
        for key in ("width", "length", "height"):
            o[key] *= s
        o["mass_kg"] *= s ** 3
        z = max(PAD_HALF + TIP_CLEARANCE, o["height"] / 2)  # pad centre at the grasp (probe.geometry)
        h = max(min(o["height"], z + PAD_HALF) - max(0.0, z - PAD_HALF), 1e-3)
        o["k"] = o["E"] * PAD_W * h / o["width"] if o["soft"] else None

    colors = ["0.95 0.8 0.1 1", "0.1 0.65 0.45 1", "0.2 0.4 0.9 1", "0.9 0.3 0.2 1"]
    # base -> world: rotate 180 deg about z (positions are not scaled: only the objects are)
    models = "".join(model(o, (-o["xy_base"][0], -o["xy_base"][1]), o["yaw_base"] + math.pi, colors[k % 4])
                     for k, o in enumerate(objs))
    os.makedirs(args.out, exist_ok=True)
    src = os.path.relpath(args.sim, args.out)
    if args.topcam:
        xy = np.mean([o["xy_base"] for o in objs], 0)
        cam_sdf, cam2base = topcam((-xy[0], -xy[1]))
        w = WORLD.format(src=src, mu=MU, models=models + cam_sdf)
        w = w.replace('    <plugin filename="gz-sim-physics-system"', SENSORS + '    <plugin filename="gz-sim-physics-system"', 1)
        open(os.path.join(args.out, "world.sdf"), "w").write(w)
        e = WORLD.format(src=src, mu=MU, models=cam_sdf)
        e = e.replace('    <plugin filename="gz-sim-physics-system"', SENSORS + '    <plugin filename="gz-sim-physics-system"', 1)
        open(os.path.join(args.out, "world_empty.sdf"), "w").write(e)
        json.dump({"cam2base_opencv": cam2base, "table_z_base": 0.0, "D": [0.0] * 5,
                   "note": "the simulated camera's exact pose: what calibrate_camera measures in the lab. "
                           "K comes from the captured camera_info."},
                  open(os.path.join(args.out, "topcam_pose.json"), "w"), indent=2)
    else:
        open(os.path.join(args.out, "world.sdf"), "w").write(WORLD.format(src=src, mu=MU, models=models))
    sid = args.scene_id or gr["scene_id"]
    json.dump({"scene_id": sid, "task": "heavy_deformable", "frame": "base", "table_z_base": 0.0,
               "objects": [{"name": o["name"], "obj_id": o["name"], "grasp": {
                   "centre_xy": o["xy_base"], "yaw": o["yaw_base"], "width": o["width"],
                   "top_z": o["height"], "height": o["height"]}} for o in objs]},
              open(os.path.join(args.out, "grasps.json"), "w"), indent=2)
    # Ground truth of the Gazebo scene, i.e. what correct robot code must find: heavy = largest
    # mass; deformable = the largest compression between the squeeze forces that the springs
    # (with their 0.8 L stop) produce, the robot's own rule.
    for o in objs:
        d = [min(f / o["k"], MAX_STRAIN * o["width"]) if o["soft"] else 0.0 for f in args.squeeze_forces]
        o["expected_compression_m"] = d[-1] - d[0]
    soft_i = int(np.argmax([o["expected_compression_m"] for o in objs]))
    json.dump({"scene_id": sid, "scale": s, "squeeze_forces_N": args.squeeze_forces, "objects": [{
        "name": o["name"], "id": o["name"], "xy_base": [round(v, 3) for v in o["xy_base"]],
        "mass_g": round(o["mass_kg"] * 1000, 2), "soft": i == soft_i,
        "expected_compression_mm": round(o["expected_compression_m"] * 1000, 2),
        "slatphys_soft": o["soft"], "E": o["E"], "spring_k_N_per_m": o["k"],
        "size_mm": [round(o["width"] * 1000, 1), round(o["length"] * 1000, 1), round(o["height"] * 1000, 1)]}
        for i, o in enumerate(objs)]}, open(os.path.join(args.out, "plan.json"), "w"), indent=2)
    print(f"scale x{s:.3f} ->", os.path.abspath(args.out))
    for o in objs:
        print(f"  {o['name']:12s} {o['width'] * 1000:5.1f} x {o['length'] * 1000:5.1f} x {o['height'] * 1000:5.1f} mm  "
              f"{o['mass_kg'] * 1000:6.1f} g  expected compression {o['expected_compression_m'] * 1000:4.1f} mm  " + (f"spring k {o['k']:.0f} N/m (20 N -> {min(20 / o['k'], MAX_STRAIN * o['width']) * 1000:.1f} mm,"
                                                  f" 60 N -> {min(60 / o['k'], MAX_STRAIN * o['width']) * 1000:.1f} mm)"
                                                  if o["soft"] else "rigid"))


if __name__ == "__main__":
    main()
